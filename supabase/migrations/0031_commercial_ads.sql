-- ============================================================
-- 10. ADMIN PODE SUBSTITUIR IMAGENS
-- ============================================================

drop policy if exists "Admins can update commercial ad images"
on storage.objects;

create policy "Admins can update commercial ad images"
on storage.objects
for update
to authenticated
using (
  bucket_id = 'commercial-ads'
  and exists (
    select 1
    from public.profiles
    where profiles.id = auth.uid()
      and profiles.role = 'admin'
  )
)
with check (
  bucket_id = 'commercial-ads'
  and exists (
    select 1
    from public.profiles
    where profiles.id = auth.uid()
      and profiles.role = 'admin'
